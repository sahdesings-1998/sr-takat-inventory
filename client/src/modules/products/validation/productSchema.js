  laboratory: z.string().optional().or(z.literal("")),
  certificateNumber: z.string().optional().or(z.literal("")),
  certificateDate: z.preprocess(coerceDateString, z.string().optional().or(z.literal(""))),
  certificateCost: z.preprocess(coerceNum, z.number().optional().default(0)),
  certificatePdf: z.string().optional().or(z.literal("")),
  certificateImages: z.string().optional().or(z.literal("")),
  certificateNotes: z.string().optional().or(z.literal("")),
  materialCost: z.preprocess(coerceNum, z.number().optional().default(0)),
  manufacturingCost: z.preprocess(coerceNum, z.number().optional().default(0)),
  packagingCost: z.preprocess(coerceNum, z.number().optional().default(0)),
  shippingCost: z.preprocess(coerceNum, z.number().optional().default(0)),
  insuranceCost: z.preprocess(coerceNum, z.number().optional().default(0)),
  otherCosts: z.preprocess(coerceNum, z.number().optional().default(0)),
