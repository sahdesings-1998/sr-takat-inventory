import { z } from "zod";

const categoryEnum = [
  "Gemstone",
  "Jewellery",
  "Watch",
  "Custom Product",
  "Accessory",
  "Ring",
  "Necklace",
  "Earrings",
  "Bracelet",
  "Pendant",
  "Other",
];

const statusEnum = [
  "Draft",
  "Available",
  "Reserved",
  "On Consignment",
  "On Memo",
  "In Production",
  "Sold",
  "Returned",
  "Archived",
  "In Stock",
  "Missing",
  "Damaged",
];

const coerceNum = (val) => {
  if (val === "" || val === null || val === undefined || isNaN(val)) return 0;
  return Number(val);
};

const coerceDateString = (val) => {
  if (!val) return "";
  if (typeof val === "string") return val.slice(0, 10);
  if (val instanceof Date) return val.toISOString().slice(0, 10);
  if (typeof val === "object" && val?.target?.value !== undefined) {
    return String(val.target.value || "").slice(0, 10);
  }
  return String(val).slice(0, 10);
};

