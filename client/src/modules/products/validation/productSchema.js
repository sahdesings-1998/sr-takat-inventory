  supplierReference: z.string().optional().or(z.literal("")),
  purchaseDate: z.preprocess(coerceDateString, z.string().optional().or(z.literal(""))),
  purchaseInvoice: z.string().optional().or(z.literal("")),
  paymentStatus: z.string().optional().or(z.literal("")),
